<script setup lang="ts">
import { computed, onBeforeUnmount, ref, watch } from 'vue';
import { ExclamationTriangleIcon } from '@heroicons/vue/24/outline';
import BaseButton from '../common/BaseButton.vue';
import FormErrorSummary from '../common/FormErrorSummary.vue';
import FormField from '../common/FormField.vue';
import TemplateSentenceBuilder from './TemplateSentenceBuilder.vue';
import {
  useComparisonTemplatesStore,
  type ComparisonTemplate,
  type PreviewSentence,
  type TemplateDraft,
  type TrendWarning,
} from '../../stores/comparisonTemplates.store';
import {
  SENTENCE_FIELD_NAMES,
  parseBody,
  readableExcerpt,
  serializeSegments,
  validateSentence,
  type SentenceField,
  type TemplateSegment,
} from '../../utils/comparisonTemplateSegments';
import { INPUT_CLASSES } from '../../utils/formStyles';
import { ApiError } from '../../utils/apiClient';

/**
 * Admin form for one comparison template (SPEC §5, §8): name, main sentence, and the three
 * variants, each built from named parts. Owns the save, the trend-keyword acknowledgment flow
 * and the debounced live preview; the parent only supplies the template (or null for a new one)
 * and reacts to `saved` / `cancel`.
 *
 * The lookup key is generated by the store and never shown. No status, code or key is ever
 * rendered; failures arrive as approved sentences from the store.
 */

const props = withDefaults(
  defineProps<{ template?: ComparisonTemplate | null; idPrefix?: string }>(),
  {
    template: null,
    idPrefix: 'templat',
  },
);

const emit = defineEmits<{
  (e: 'saved', template: ComparisonTemplate): void;
  (e: 'cancel'): void;
  /** True while a save is in flight, so the host can refuse to dismiss the editor. */
  (e: 'busy', value: boolean): void;
}>();

const store = useComparisonTemplatesStore();

const SENTENCE_FIELDS: readonly SentenceField[] = ['body', 'trendNaik', 'trendTurun', 'trendTetap'];

const nameInput = ref<HTMLInputElement | null>(null);
const baseUpdatedAt = ref(props.template?.updatedAt ?? '');
const label = ref(props.template?.label ?? '');
const segments = ref<Record<SentenceField, TemplateSegment[]>>({
  body: parseBody(props.template?.body ?? ''),
  trendNaik: parseBody(props.template?.trendNaik ?? ''),
  trendTurun: parseBody(props.template?.trendTurun ?? ''),
  trendTetap: parseBody(props.template?.trendTetap ?? ''),
});

const submitted = ref(false);
const saving = ref(false);
const reloadingLatest = ref(false);
const formBusy = computed(() => saving.value || reloadingLatest.value);
watch(formBusy, (value) => emit('busy', value));
const serverError = ref('');
const isStale = ref(false);
const staleMessage = ref('');
const touched = ref<Set<string>>(new Set());

const fieldId = (name: string): string => `${props.idPrefix}-${name}`;

const serialized = computed<Record<SentenceField, string>>(() => ({
  body: serializeSegments(segments.value.body).trim(),
  trendNaik: serializeSegments(segments.value.trendNaik).trim(),
  trendTurun: serializeSegments(segments.value.trendTurun).trim(),
  trendTetap: serializeSegments(segments.value.trendTetap).trim(),
}));

// What the form held when it opened, so the host can tell whether closing would lose edits.
const baseline = ref(
  JSON.stringify([
    label.value.trim(),
    ...SENTENCE_FIELDS.map((field) => serialized.value[field]),
  ]),
);
const isDirty = (): boolean =>
  JSON.stringify([label.value.trim(), ...SENTENCE_FIELDS.map((f) => serialized.value[f])]) !==
  baseline.value;

function focusNameInput(): void {
  nameInput.value?.focus();
}

defineExpose({ isDirty, focusNameInput });

const labelError = computed(() => {
  const value = label.value.trim();
  if (value === '') return 'Nama templat wajib diisi.';
  if (value.length > 255) return 'Nama templat terlalu panjang. Persingkat namanya.';
  const lower = value.toLowerCase();
  const duplicate = store.templates.some(
    (t) => Boolean(t) && t.id !== props.template?.id && t.label.trim().toLowerCase() === lower,
  );
  if (duplicate) return 'Nama templat sudah dipakai. Gunakan nama lain.';
  return undefined;
});

const sentenceErrors = computed(() => {
  const errors: Partial<Record<SentenceField, string>> = {};
  for (const field of SENTENCE_FIELDS) {
    errors[field] = validateSentence(field, segments.value[field]);
  }
  return errors;
});

const hasLocalErrors = computed(
  () => labelError.value !== undefined || SENTENCE_FIELDS.some((f) => sentenceErrors.value[f]),
);

function shown(name: string, message: string | undefined): string | undefined {
  return submitted.value || touched.value.has(name) ? message : undefined;
}

const visibleLabelError = computed(() => shown('label', labelError.value));
const visibleSentenceError = (field: SentenceField): string | undefined =>
  shown(field, sentenceErrors.value[field]);

const summaryErrors = computed(() => {
  if (!submitted.value) return [];
  const entries: Array<{ fieldId: string; message: string }> = [];
  if (labelError.value) entries.push({ fieldId: fieldId('nama'), message: labelError.value });
  for (const field of SENTENCE_FIELDS) {
    const message = sentenceErrors.value[field];
    if (message) entries.push({ fieldId: fieldId(field), message });
  }
  return entries;
});

watch(label, () => touched.value.add('label'));
for (const field of SENTENCE_FIELDS) {
  watch(
    () => serialized.value[field],
    () => touched.value.add(field),
  );
}

// --- Trend-keyword acknowledgment ---------------------------------------------------------

const pendingWarnings = ref<TrendWarning[]>([]);
const confirmed = ref<Record<string, boolean>>({});
const warningNotice = ref('');
const warningPanel = ref<HTMLElement | null>(null);

const allConfirmed = computed(
  () =>
    pendingWarnings.value.length > 0 &&
    pendingWarnings.value.every((warning) => confirmed.value[warning.ackKey] === true),
);
const awaitingConfirmation = computed(
  () => pendingWarnings.value.length > 0 && !allConfirmed.value,
);

// An acknowledgment is bound to the exact wording it was shown for, so any edit to the main
// sentence voids it; the server would reject the stale keys anyway.
watch(
  () => serialized.value.body,
  () => {
    // Any edit to the sentence makes a leftover "confirmation cancelled" notice stale.
    if (pendingWarnings.value.length === 0) {
      warningNotice.value = '';
      return;
    }
    pendingWarnings.value = [];
    confirmed.value = {};
    warningNotice.value =
      'Susunan kalimat berubah, jadi konfirmasi sebelumnya dibatalkan. Simpan lagi untuk memeriksa ulang.';
  },
);

function warningText(warning: TrendWarning): string {
  return `Kalimat ini menyatakan perubahan atau perbandingan ("${warning.phrase}") di luar bagian yang mengikuti angka. Kata itu akan tampil sama persis apa pun arah datanya dan bisa menjadi tidak benar saat angkanya berubah. Periksa kembali sebelum menyimpan.`;
}

// --- Save ---------------------------------------------------------------------------------

function buildDraft(): TemplateDraft {
  return {
    label: label.value.trim(),
    body: serialized.value.body,
    trendNaik: serialized.value.trendNaik,
    trendTurun: serialized.value.trendTurun,
    trendTetap: serialized.value.trendTetap,
  };
}

async function handleSubmit(): Promise<void> {
  if (formBusy.value) return;
  isPreviewPaused.value = false;
  submitted.value = true;
  serverError.value = '';
  warningNotice.value = '';
  isStale.value = false;
  staleMessage.value = '';
  if (hasLocalErrors.value || awaitingConfirmation.value) return;

  saving.value = true;
  const acknowledged = allConfirmed.value ? pendingWarnings.value.map((w) => w.ackKey) : [];
  try {
    const draft = buildDraft();
    const outcome = props.template
      ? await store.updateTemplate(
          props.template.id,
          draft,
          baseUpdatedAt.value,
          acknowledged,
        )
      : await store.createTemplate(draft, acknowledged);

    if (outcome.ok) {
      emit('saved', outcome.template);
      return;
    }
    if (outcome.kind === 'ack') {
      const previous = confirmed.value;
      pendingWarnings.value = outcome.warnings;
      confirmed.value = Object.fromEntries(
        outcome.warnings.map((warning) => [warning.ackKey, previous[warning.ackKey] === true]),
      );
      warningNotice.value = '';
      requestAnimationFrame(() => warningPanel.value?.focus());
      return;
    }
    if (outcome.kind === 'stale') {
      isStale.value = true;
      staleMessage.value = outcome.message;
      return;
    }
    // The draft stays exactly as typed; only the banner changes.
    serverError.value = outcome.message;
  } finally {
    saving.value = false;
  }
}

const lastSyncedUpdatedAt = ref<string | null>(props.template?.updatedAt ?? null);
let isUnmounted = false;

function syncFromTemplate(fresh: ComparisonTemplate | null): void {
  isPreviewPaused.value = false;
  lastSyncedUpdatedAt.value = fresh?.updatedAt ?? null;
  baseUpdatedAt.value = fresh?.updatedAt ?? '';
  label.value = fresh?.label ?? '';
  segments.value = {
    body: parseBody(fresh?.body ?? ''),
    trendNaik: parseBody(fresh?.trendNaik ?? ''),
    trendTurun: parseBody(fresh?.trendTurun ?? ''),
    trendTetap: parseBody(fresh?.trendTetap ?? ''),
  };
  baseline.value = JSON.stringify([
    label.value.trim(),
    ...SENTENCE_FIELDS.map((field) => serializeSegments(segments.value[field]).trim()),
  ]);
  touched.value.clear();
  submitted.value = false;
  isStale.value = false;
  staleMessage.value = '';
  serverError.value = '';
  pendingWarnings.value = [];
  confirmed.value = {};
  warningNotice.value = '';
}

watch(
  () => props.template?.id,
  (nextId, prevId) => {
    if (nextId !== prevId) {
      syncFromTemplate(props.template ?? null);
    }
  },
);

async function handleReloadLatest(): Promise<void> {
  if (reloadingLatest.value || saving.value || !props.template) return;
  const targetId = props.template.id;
  isPreviewPaused.value = false;
  reloadingLatest.value = true;
  serverError.value = '';
  let fetched = false;
  try {
    fetched = await store.fetchTemplates(true);
  } finally {
    reloadingLatest.value = false;
  }

  if (isUnmounted || props.template?.id !== targetId) return;

  if (!fetched) {
    serverError.value = store.error ?? 'Gagal memuat versi terbaru templat. Silakan coba lagi.';
    return;
  }

  const fresh = store.templates.find((t) => t.id === targetId);
  if (!fresh) {
    serverError.value = store.error ?? 'Gagal memuat versi terbaru templat. Silakan coba lagi.';
    return;
  }

  if (isDirty() && typeof window !== 'undefined' && typeof window.confirm === 'function') {
    const ok = window.confirm(
      'Perubahan yang belum disimpan akan digantikan dengan versi terbaru. Lanjutkan?',
    );
    if (!ok) return;
  }

  syncFromTemplate(fresh);
}

// --- Live preview -------------------------------------------------------------------------

const PREVIEW_DEBOUNCE_MS = 700;

const previewStatus = ref<'incomplete' | 'loading' | 'ready' | 'error'>('incomplete');
const previews = ref<PreviewSentence[]>([]);
const previewProblems = ref<string[]>([]);
const previewError = ref('');
const isPreviewPaused = ref(false);
let previewTimer: ReturnType<typeof setTimeout> | null = null;
let previewAbort: AbortController | null = null;
let previewSeq = 0;

const sentencesComplete = computed(() => SENTENCE_FIELDS.every((f) => !sentenceErrors.value[f]));

function cancelPreview(): void {
  if (previewTimer) clearTimeout(previewTimer);
  previewTimer = null;
  previewAbort?.abort();
  previewAbort = null;
}

async function runPreview(): Promise<void> {
  const seq = ++previewSeq;
  previewAbort = new AbortController();
  previewStatus.value = 'loading';
  try {
    const result = await store.previewTemplate(
      {
        body: serialized.value.body,
        trendNaik: serialized.value.trendNaik,
        trendTurun: serialized.value.trendTurun,
        trendTetap: serialized.value.trendTetap,
      },
      previewAbort.signal,
    );
    if (seq !== previewSeq) return;
    previewProblems.value = result.valid ? [] : result.problems.map((p) => p.message);
    previews.value = result.valid ? result.previews : [];
    previewStatus.value = result.valid ? 'ready' : 'incomplete';
  } catch (error) {
    if (seq !== previewSeq) return;
    if (error instanceof DOMException && error.name === 'AbortError') return;
    previews.value = [];
    previewProblems.value = [];
    previewStatus.value = 'error';
    if (error instanceof ApiError && error.status === 401) {
      isPreviewPaused.value = true;
      previewError.value =
        'Sesi Anda telah berakhir. Masuk kembali untuk memuat pratinjau.';
    } else if (error instanceof ApiError && error.status === 429) {
      if (typeof error.retryAfterSeconds === 'number' && error.retryAfterSeconds > 0) {
        previewError.value = `Terlalu banyak pratinjau. Coba lagi dalam ${error.retryAfterSeconds} detik.`;
      } else {
        previewError.value = 'Terlalu banyak pratinjau. Tunggu sebentar lalu coba lagi.';
      }
    } else {
      previewError.value =
        'Pratinjau belum bisa dimuat. Anda tetap bisa menyimpan; coba ubah kalimat lagi untuk memuat ulang pratinjau.';
    }
  }
}

function schedulePreview(): void {
  cancelPreview();
  if (isPreviewPaused.value) return;
  previewSeq += 1;
  previewError.value = '';
  if (!sentencesComplete.value) {
    previews.value = [];
    previewProblems.value = [];
    previewStatus.value = 'incomplete';
    return;
  }
  previewStatus.value = 'loading';
  previewTimer = setTimeout(() => void runPreview(), PREVIEW_DEBOUNCE_MS);
}

watch(() => SENTENCE_FIELDS.map((f) => serialized.value[f]).join('\u0000'), schedulePreview, {
  immediate: true,
});

onBeforeUnmount(() => {
  isUnmounted = true;
  cancelPreview();
});

// Only a short status is announced; the sentences themselves sit outside the live region so
// every debounced update does not re-read up to four full sentences.
const previewAnnouncement = computed(() => {
  if (previewStatus.value === 'loading') return 'Memperbarui pratinjau';
  if (previewStatus.value === 'ready') return 'Pratinjau diperbarui';
  if (previewStatus.value === 'error') return 'Pratinjau belum bisa dimuat';
  return '';
});

const usageNote = computed(() => {
  const count = props.template?.usageCount ?? 0;
  return count > 0
    ? `Templat ini dipakai ${count} indikator. Perubahan yang disimpan langsung tampil di halaman publik.`
    : '';
});
</script>

<template>
  <form class="space-y-6" novalidate data-test="template-form" @submit.prevent="handleSubmit">
    <FormErrorSummary
      v-if="summaryErrors.length > 0 || serverError"
      :errors="summaryErrors"
      :form-error="serverError"
    />

    <div
      v-if="isStale"
      class="rounded-card border-status-warning-border bg-status-warning-surface border p-4 text-sm"
      data-test="stale-banner"
      role="alert"
    >
      <div class="flex items-start gap-3">
        <ExclamationTriangleIcon class="text-status-warning h-5 w-5 shrink-0" aria-hidden="true" />
        <div class="space-y-2">
          <p class="text-brand-navy font-semibold">
            {{ staleMessage || 'Data ini baru saja diubah oleh pengguna lain.' }}
          </p>
          <p class="text-text-muted">
            Muat ulang untuk melihat versi terbaru; isian Anda tetap tersimpan di formulir sebelum dimuat.
          </p>
          <BaseButton
            type="button"
            variant="secondary"
            size="sm"
            class="min-h-11"
            data-test="reload-latest"
            :disabled="formBusy"
            @click="handleReloadLatest"
          >
            Muat versi terbaru
          </BaseButton>
        </div>
      </div>
    </div>

    <p
      v-if="usageNote"
      class="rounded-btn border-border bg-surface-muted text-brand-navy border px-3 py-2 text-sm"
      data-test="usage-note"
    >
      {{ usageNote }}
    </p>

    <FormField
      :id="fieldId('nama')"
      label="Nama templat"
      required
      hint="Nama untuk membedakan templat ini saat Editor memilihnya."
      :error="visibleLabelError"
      v-slot="{ describedBy, invalid }"
    >
      <input
        :id="fieldId('nama')"
        ref="nameInput"
        v-model="label"
        type="text"
        maxlength="255"
        :disabled="formBusy"
        :class="INPUT_CLASSES"
        :aria-describedby="describedBy"
        :aria-invalid="invalid ? 'true' : undefined"
      />
    </FormField>

    <p class="text-text-muted text-sm">
      Susun kalimat dari teks biasa dan bagian otomatis. Angka, periode, serta kata naik, turun,
      atau tetap terisi sendiri sesuai data indikator.
    </p>

    <TemplateSentenceBuilder
      v-model="segments.body"
      mode="body"
      :id-prefix="fieldId('body')"
      field="body"
      :label="SENTENCE_FIELD_NAMES.body"
      hint="Kalimat utama yang tampil di halaman publik. Wajib memuat satu bagian “Keterangan perubahan”."
      :error="visibleSentenceError('body')"
      :disabled="formBusy"
    />

    <div class="grid gap-4 lg:grid-cols-1">
      <TemplateSentenceBuilder
        v-model="segments.trendNaik"
        mode="variant"
        :id-prefix="fieldId('trendNaik')"
        field="trendNaik"
        :label="SENTENCE_FIELD_NAMES.trendNaik"
        hint="Mengisi bagian “Keterangan perubahan” bila nilai sekarang lebih besar dari nilai sebelumnya."
        :error="visibleSentenceError('trendNaik')"
        :disabled="formBusy"
      />
      <TemplateSentenceBuilder
        v-model="segments.trendTurun"
        mode="variant"
        :id-prefix="fieldId('trendTurun')"
        field="trendTurun"
        :label="SENTENCE_FIELD_NAMES.trendTurun"
        hint="Mengisi bagian “Keterangan perubahan” bila nilai sekarang lebih kecil dari nilai sebelumnya."
        :error="visibleSentenceError('trendTurun')"
        :disabled="formBusy"
      />
      <TemplateSentenceBuilder
        v-model="segments.trendTetap"
        mode="variant"
        :id-prefix="fieldId('trendTetap')"
        field="trendTetap"
        :label="SENTENCE_FIELD_NAMES.trendTetap"
        hint="Mengisi bagian “Keterangan perubahan” bila kedua nilai sama."
        :error="visibleSentenceError('trendTetap')"
        :disabled="formBusy"
      />
    </div>

    <section
      class="rounded-card border-border bg-surface-muted border p-4"
      :aria-labelledby="fieldId('pratinjau-judul')"
      data-test="preview"
    >
      <h3 :id="fieldId('pratinjau-judul')" class="text-brand-navy text-sm font-semibold">
        Pratinjau kalimat
      </h3>
      <p class="text-text-muted mt-1 text-xs">
        Contoh dengan angka rekaan, dibuat dengan cara yang sama seperti di halaman publik.
      </p>

      <p class="sr-only" role="status" aria-live="polite" data-test="preview-status">
        {{ previewAnnouncement }}
      </p>

      <div :aria-busy="previewStatus === 'loading'" class="mt-3 space-y-3">
        <p
          v-if="previewStatus === 'incomplete'"
          class="text-text-muted text-sm"
          data-test="preview-incomplete"
        >
          <template v-if="previewProblems.length === 0">
            Pratinjau muncul setelah susunan kalimat dan ketiga teks perubahan lengkap.
          </template>
          <template v-else>{{ previewProblems.join(' ') }}</template>
        </p>
        <p
          v-else-if="previewStatus === 'loading' && previews.length === 0"
          class="text-text-muted text-sm"
        >
          Menyiapkan pratinjau…
        </p>
        <p
          v-else-if="previewStatus === 'loading' && previews.length > 0"
          class="text-text-muted text-sm"
          data-test="preview-updating"
        >
          Memperbarui pratinjau…
        </p>
        <p
          v-else-if="previewStatus === 'error'"
          class="text-status-error text-sm"
          data-test="preview-error"
        >
          {{ previewError }}
        </p>

        <ul v-if="previews.length > 0" class="space-y-3">
          <li
            v-for="item in previews"
            :key="item.title"
            class="rounded-btn border-border bg-surface border p-3 transition-opacity duration-200"
            :class="{ 'opacity-60': previewStatus === 'loading' }"
            data-test="preview-item"
          >
            <p class="text-text-muted text-xs font-semibold">{{ item.title }}</p>
            <p v-if="item.text" class="text-brand-navy mt-1 text-sm">{{ item.text }}</p>
            <p v-else class="text-text-muted mt-1 text-sm" data-test="preview-note">
              {{ item.note }}
            </p>
          </li>
        </ul>
      </div>
    </section>

    <section
      v-if="pendingWarnings.length > 0 || warningNotice"
      ref="warningPanel"
      tabindex="-1"
      class="rounded-card border-status-warning-border bg-status-warning-surface border p-4"
      data-test="trend-warnings"
    >
      <p class="text-status-warning flex items-center gap-2 text-sm font-semibold">
        <ExclamationTriangleIcon class="h-5 w-5 shrink-0" aria-hidden="true" />
        <span v-if="pendingWarnings.length > 0">Periksa dulu sebelum menyimpan</span>
        <span v-else>Konfirmasi dibatalkan</span>
      </p>
      <p v-if="warningNotice" class="text-status-warning mt-2 text-sm" data-test="warning-notice">
        {{ warningNotice }}
      </p>

      <ul v-if="pendingWarnings.length > 0" class="mt-3 space-y-3">
        <li
          v-for="(warning, index) in pendingWarnings"
          :key="warning.ackKey"
          class="rounded-btn border-status-warning-border bg-surface border p-3"
          data-test="trend-warning"
        >
          <p class="text-brand-navy text-sm">{{ warningText(warning) }}</p>
          <p class="text-text-muted mt-1 text-xs">
            Kutipan: “{{ readableExcerpt(warning.excerpt) }}”
          </p>
          <label
            :for="fieldId(`konfirmasi-${index}`)"
            class="text-brand-navy mt-2 flex min-h-11 cursor-pointer items-center gap-3 text-sm font-medium"
            data-test="confirm-label"
          >
            <input
              :id="fieldId(`konfirmasi-${index}`)"
              v-model="confirmed[warning.ackKey]"
              type="checkbox"
              :disabled="formBusy"
              class="border-border-strong text-brand-navy focus-visible:outline-focus-ring h-5 w-5 shrink-0 rounded-xs focus-visible:outline-2 focus-visible:outline-offset-2"
            />
            <span>
              Saya sudah memeriksa kata "{{ warning.phrase }}" ini dan tetap ingin menyimpannya.
            </span>
          </label>
        </li>
      </ul>
    </section>

    <div
      class="border-border flex flex-col-reverse gap-3 border-t pt-4 sm:flex-row sm:items-center sm:justify-end"
    >
      <p
        v-if="awaitingConfirmation"
        :id="fieldId('simpan-bantuan')"
        class="text-text-muted text-xs sm:mr-auto"
        data-test="confirm-help"
      >
        Centang konfirmasi pada setiap peringatan di atas untuk melanjutkan.
      </p>
      <BaseButton
        variant="secondary"
        size="md"
        class="min-h-11"
        :disabled="formBusy"
        @click="emit('cancel')"
      >
        Batal
      </BaseButton>
      <BaseButton
        type="submit"
        size="md"
        class="min-h-11"
        :disabled="formBusy || awaitingConfirmation"
        :aria-describedby="awaitingConfirmation ? fieldId('simpan-bantuan') : undefined"
        data-test="save"
      >
        {{ saving ? 'Menyimpan…' : 'Simpan templat' }}
      </BaseButton>
    </div>
  </form>
</template>
